function [clean, channel] = add_bellhop_channel(s, channelDir)

if ~exist(channelDir, 'dir'), mkdir(channelDir); end

fc = signal_center_frequency(s.sig);
[ssp, bdry, pos, beam, cInt, rMax, c] = ...
    build_ssp(s.z, s.temp, s.sd, s.rd, s.rr);
env = fullfile(channelDir, [s.id '.env']);
arr = fullfile(channelDir, [s.id '.arr']);
write_env(env, 'BELLHOP', s.id, fc, ssp, bdry, pos, beam, cInt, rMax);

old = pwd;
restoreFolder = onCleanup(@() cd(old));
cd(channelDir);
bellhop(s.id);
[arrivals, ~] = read_arrivals_local(arr, 500);

v = s.receiver_velocity_mps;
[clean, delayS, amp, alpha] = ...
    delayandsum_doppler(s.tx, s.fs, arrivals, v, 1500, 1, 1, 1);
assert(numel(clean) == round(s.fs * s.dur), ...
    '信道输出长度与设定总时长不一致。');

channel = struct('simulator', 'Bellhop', ...
    'env_file', [s.id '.env'], 'arr_file', [s.id '.arr'], ...
    'sound_speed_mps', c(:).', 'source_depth_m', s.sd, ...
    'receiver_depth_m', s.rd, 'range_km', s.rr, ...
    'receiver_velocity_mps', v(:).', 'doppler_factor', alpha(:).', ...
    'bellhop_frequency_hz', fc, 'multipath_count', numel(delayS), ...
    'path_delay_s', delayS(:).', 'path_amplitude_real', real(amp(:)).', ...
    'path_amplitude_imag', imag(amp(:)).');
end
