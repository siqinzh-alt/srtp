function meta = save_output(rx, s, channel, noiseInfo, dataRoot, datasetName)
%SAVE_OUTPUT 创建四类输出目录，并写入 WAV、时频图、JSON 元数据。

dirs.audio = fullfile(dataRoot, 'audio');
dirs.spectrogram = fullfile(dataRoot, 'spectrogram');
dirs.metadata = fullfile(dataRoot, 'metadata');
dirs.channel = fullfile(dataRoot, 'channel');
for path = {dirs.audio, dirs.spectrogram, dirs.metadata, dirs.channel}
    if ~exist(path{1}, 'dir'), mkdir(path{1}); end
end

wav = fullfile(dirs.audio, [s.id '.wav']);
png = fullfile(dirs.spectrogram, [s.id '.png']);
json = fullfile(dirs.metadata, [s.id '.json']);
audiowrite(wav, rx, s.fs, 'BitsPerSample', 16);
saveSpectrogram(rx, s.fs, png, s.image_px);

meta = struct('id', s.id, 'label', s.label, 'class_label', s.class_label, ...
    'group_id', s.group_id, 'split', s.split, 'sample_rate_hz', s.fs, ...
    'duration_s', s.dur, 'audio_path', relPath(datasetName, 'audio', [s.id '.wav']), ...
    'spectrogram_path', relPath(datasetName, 'spectrogram', [s.id '.png']), ...
    'metadata_path', relPath(datasetName, 'metadata', [s.id '.json']), ...
    'source', s.source, 'woa', s.woa, ...
    'ssp', struct('depth_m', s.z(:).', 'temperature_c', s.temp(:).', ...
    'sound_speed_mps', channel.sound_speed_mps), 'receiver', noiseInfo, ...
    'channel', struct('simulator', channel.simulator, ...
    'env_path', relPath(datasetName, 'channel', channel.env_file), ...
    'arr_path', relPath(datasetName, 'channel', channel.arr_file), ...
    'source_depth_m', channel.source_depth_m, ...
    'receiver_depth_m', channel.receiver_depth_m, 'range_km', channel.range_km, ...
    'receiver_velocity_mps', channel.receiver_velocity_mps, ...
    'doppler_factor', channel.doppler_factor, ...
    'bellhop_frequency_hz', channel.bellhop_frequency_hz, ...
    'multipath_count', channel.multipath_count, ...
    'path_delay_s', channel.path_delay_s, ...
    'path_amplitude_real', channel.path_amplitude_real, ...
    'path_amplitude_imag', channel.path_amplitude_imag));
writeJson(json, meta);
end

function saveSpectrogram(x, fs, path, px)
fig = figure('Visible', 'off', 'Color', 'w', ...
    'Position', [100 100 px px]);
spectrogram(x, hann(512, 'periodic'), 448, 1024, fs, 'yaxis');
ax = gca;
ylim(ax, [0 fs/2] / 1000);
axis(ax, 'off');
set(ax, 'Units', 'normalized', 'Position', [0 0 1 1]);
exportgraphics(ax, path, 'Resolution', 96);
close(fig);
end

function path = relPath(datasetName, folder, file)
path = fullfile('output', 'datasets', datasetName, folder, file);
end

function writeJson(path, value)
id = fopen(path, 'w');
assert(id ~= -1, 'Cannot write %s.', path);
closer = onCleanup(@() fclose(id));
fprintf(id, '%s\n', jsonencode(value));
end
